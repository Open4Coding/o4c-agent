// Regenerates src/graph/libraryMethods.ts: every method name the TypeScript standard library
// declares on its interfaces (Array, Map, String, Promise, Date, ...), read from the compiler's own
// lib files. DOM is left out on purpose - see the module's doc comment.
// Usage: node scripts/library-methods.mjs
import { createRequire } from 'node:module';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ts = createRequire(join(root, 'package.json'))('typescript');
const libDir = dirname(ts.sys.resolvePath(join(root, 'node_modules/typescript/lib/lib.d.ts')));
const files = readdirSync(libDir).filter((f) => /^lib\.(es\d+|esnext|es5|decorators|scripthost)[\w.]*\.d\.ts$/.test(f));

const names = new Set();
for (const f of files) {
  const sf = ts.createSourceFile(f, readFileSync(join(libDir, f), 'utf8'), ts.ScriptTarget.Latest, false);
  const visit = (node) => {
    if ((ts.isMethodSignature(node) || ts.isPropertySignature(node)) && node.name && ts.isIdentifier(node.name)) {
      // A property counts only if it holds a function, since only those can be called.
      if (ts.isMethodSignature(node) || (node.type && ts.isFunctionTypeNode(node.type))) names.add(node.name.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
}

const lines = [];
let line = ' ';
for (const name of [...names].sort()) {
  const item = ` '${name}',`;
  if (line.length + item.length > 100) {
    lines.push(line);
    line = ' ';
  }
  line += item;
}
lines.push(line);

const source = `/**
 * Method names the ECMAScript standard library declares: ${names.size} of them, read from the
 * \`lib.es*.d.ts\` files of TypeScript ${ts.version}. Generated by \`scripts/library-methods.mjs\`; edit
 * that, not this.
 *
 * \`resolve.ts\` reads it for one rule: \`o.get()\`, \`o.push()\`, \`o.trim()\` resolve only to a
 * method in the calling file. A receiver of unknown type calling a name the standard library
 * defines is, more often than not, calling the standard library - and handing it the repository's
 * one \`get\` was the largest class of wrong answer the stricter grading line found (2026-10-27).
 *
 * The DOM lib is left out: it adds names like \`append\`, \`remove\` and \`close\` that repositories
 * define for themselves far more often than they call them on a DOM node.
 */
export const ECMASCRIPT_LIBRARY_METHODS: ReadonlySet<string> = new Set([
${lines.join('\n')}
]);
`;
writeFileSync(join(root, 'src/graph/libraryMethods.ts'), source);
console.log(`${files.length} lib files, ${names.size} method names`);
