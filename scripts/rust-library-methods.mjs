// Regenerates src/graph/rustLibraryMethods.ts: every stable method name (a function taking `self`)
// that Rust's core, alloc and std declare, read from the toolchain's rustdoc JSON.
// Needs: rustup toolchain install nightly --profile minimal --component rust-docs-json
// Usage: node scripts/rust-library-methods.mjs
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const installed = join(homedir(), '.cargo', 'bin', process.platform === 'win32' ? 'rustup.exe' : 'rustup');
const rustup = existsSync(installed) ? installed : 'rustup';
const sysroot = execFileSync(rustup, ['run', 'nightly', 'rustc', '--print', 'sysroot'], { encoding: 'utf8' }).trim();
const rustc = execFileSync(rustup, ['run', 'nightly', 'rustc', '--version'], { encoding: 'utf8' }).trim();
const jsonDir = join(sysroot, 'share', 'doc', 'rust', 'json');

const names = new Set();
for (const crate of ['core', 'alloc', 'std']) {
  const doc = JSON.parse(readFileSync(join(jsonDir, `${crate}.json`), 'utf8'));
  for (const item of Object.values(doc.index)) {
    const fn = item.inner?.function;
    if (!fn || item.crate_id !== 0 || !item.name) continue;
    // A method is what `x.f()` can reach: its first parameter is `self`.
    if (fn.sig.inputs[0]?.[0] !== 'self') continue;
    if (item.visibility !== 'public' && item.visibility !== 'default') continue;
    // Nightly-only methods are not what a repository's code calls.
    if (!item.stability?.level?.stable) continue;
    names.add(item.name);
  }
}

const lines = [];
let line = ' ';
for (const name of [...names].sort()) {
  const entry = ` '${name}',`;
  if (line.length + entry.length > 100) {
    lines.push(line);
    line = ' ';
  }
  line += entry;
}
lines.push(line);

const source = `/**
 * Stable method names Rust's \`core\`, \`alloc\` and \`std\` declare: ${names.size} of them, read from the
 * rustdoc JSON of ${rustc}.
 * Generated by \`scripts/rust-library-methods.mjs\`; edit that, not this.
 *
 * The Rust counterpart of \`libraryMethods.ts\`: \`x.unwrap()\`, \`v.iter()\`, \`it.collect()\` resolve
 * only to a method in the calling file. Without it, telling \`f()\` from \`o.f()\` in Rust handed
 * those calls to the repository's one namesake - about half of the edges it added were wrong
 * (2026-10-27, \`0003.SELF-SURVEY-39-REPOS.md\` finding 3).
 */
export const RUST_LIBRARY_METHODS: ReadonlySet<string> = new Set([
${lines.join('\n')}
]);
`;
writeFileSync(join(root, 'src/graph/rustLibraryMethods.ts'), source);
console.log(`${names.size} method names from ${rustc}`);
